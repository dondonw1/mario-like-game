import { createRequire } from 'module';
import { execSync } from 'child_process';
import fs from 'fs';
const require = createRequire(import.meta.url);
const { chromium } = require(execSync('npm root -g').toString().trim() + '/playwright-core');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9333');
const ctx = browser.contexts()[0];
const page = ctx.pages().find(p => p.url().includes('github.io'));
console.log('url:', page.url());
const bad = [], errs = [];
page.on('response', r => { if (r.status() >= 400) bad.push(r.status() + ' ' + r.url()); });
page.on('pageerror', e => errs.push(String(e.message)));
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
console.log('hook:', await page.evaluate(() => ({ game: typeof __game !== 'undefined', state: __game && __game.state, canvas: !!document.getElementById('screen') })));
const shot = async n => { const d = await page.evaluate(() => document.getElementById('screen').toDataURL('image/png').split(',')[1]); fs.writeFileSync(n, Buffer.from(d, 'base64')); };
await shot('pages-title.png');
await page.keyboard.press('Enter');
await page.waitForTimeout(2500);
console.log('after Enter:', await page.evaluate(() => ({ state: __game.state, world: __game.level && __game.level.name, lives: __game.player && __game.player.lives })));
await shot('pages-play.png');
console.log('bad responses:', bad.length ? bad.join('\n') : 'none');
console.log('page errors:', errs.length ? errs.join('\n') : 'none');
process.exit(0);
