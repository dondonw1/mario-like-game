import { createRequire } from 'module';
import { execSync } from 'child_process';
import fs from 'fs';
const require = createRequire(import.meta.url);
const { chromium } = require(execSync('npm root -g').toString().trim() + '/playwright-core');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9333');
const page = browser.contexts()[0].pages().find(p => p.url().includes('8123'));
const errs = []; page.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(400);
await page.keyboard.press('Enter');
await page.waitForTimeout(400);
await page.evaluate(() => __game.startLevel(3, { score: 0, coins: 0, lives: 5, power: 2 }));
await page.waitForTimeout(2400);
const shot = async n => { const d = await page.evaluate(() => document.getElementById('screen').toDataURL('image/png').split(',')[1]); fs.writeFileSync(n + '.png', Buffer.from(d, 'base64')); };
console.log('start:', await page.evaluate(() => ({ st: __game.state, name: __game.level.name, lava: __game.level.lava.length, bars: __game.level.firebars.length, pods: __game.level.podoboos.length, bowser: __game.entities.filter(e => e.kind === 'bowser').length })));
await shot('test/l14-start');
await page.evaluate(() => { __game.teleport(20, 12); __game.setPower(2); });
await page.waitForTimeout(900);
await shot('test/l14-lava');
await page.evaluate(() => __game.teleport(120, 12));
await page.waitForTimeout(1400);
await shot('test/l14-bridge');
console.log('bridge:', await page.evaluate(() => ({ axe: __game.level.axe.x, bx: Math.round(__game.entities.find(e=>e.kind==='bowser').x), hp: __game.entities.find(e=>e.kind==='bowser').hp, flames: __game.entities.filter(e=>e.kind==='flame').length, st: __game.player.state })));
console.log(errs.length ? errs.slice(0,6).join('\n') : 'no errors');
process.exit(0);
