import { createRequire } from 'module';
import { execSync } from 'child_process';
import fs from 'fs';
const require = createRequire(import.meta.url);
const { chromium } = require(execSync('npm root -g').toString().trim() + '/playwright-core');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9333');
const page = browser.contexts()[0].pages().find(p => p.url().includes('8123'));
const errs = []; page.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(400);
await page.keyboard.press('Enter');
await page.waitForTimeout(400);
await page.evaluate(() => __game.startLevel(2, { score: 0, coins: 0, lives: 5, power: 0 }));
await page.waitForTimeout(2400);
const shot = async n => { const d = await page.evaluate(() => document.getElementById('screen').toDataURL('image/png').split(',')[1]); fs.writeFileSync(n + '.png', Buffer.from(d, 'base64')); };
console.log('start:', await page.evaluate(() => ({ st: __game.state, name: __game.level.name, lifts: __game.level.lifts.length, x: Math.round(__game.player.x) })));
await shot('test/l13-start');
await page.evaluate(() => __game.teleport(24, 11));
await page.waitForTimeout(600);
await shot('test/l13-pillars');
/* ride a lift: stand under it */
await page.evaluate(() => { __game.teleport(56, 12); });
await page.waitForTimeout(2500);
console.log('lift area:', await page.evaluate(() => ({ y: Math.round(__game.level.lifts[0].y), py: Math.round(__game.player.y), standing: __game.player.standing, cheeps: __game.entities.filter(e => e.kind === 'cheep').length })));
await shot('test/l13-lift');
await page.waitForTimeout(2500);
console.log('cheeps:', await page.evaluate(() => __game.entities.filter(e => e.kind === 'cheep').map(e => ({ x: Math.round(e.x - __game.vX), y: Math.round(e.y), vy: +e.vy.toFixed(1) }))));
await shot('test/l13-cheep');
console.log(errs.length ? errs.slice(0,5).join('\n') : 'no errors');
process.exit(0);
