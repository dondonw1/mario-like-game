import { createRequire } from 'module';
import { execSync } from 'child_process';
import fs from 'fs';
const require = createRequire(import.meta.url);
const { chromium } = require(execSync('npm root -g').toString().trim() + '/playwright-core');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9333');
const page = browser.contexts()[0].pages().find(p => p.url().includes('8123'));
const errs = []; page.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(600);
await page.keyboard.press('Enter');
await page.waitForTimeout(400);
await page.evaluate(() => __game.startLevel(1, { score: 0, coins: 0, lives: 5, power: 0 }));
await page.waitForTimeout(2400);
const shot = async n => { const d = await page.evaluate(() => document.getElementById('screen').toDataURL('image/png').split(',')[1]); fs.writeFileSync(n + '.png', Buffer.from(d, 'base64')); };
console.log('lifts:', await page.evaluate(() => __game.level.lifts.length));
await page.evaluate(() => { for (const e of __game.entities) if (Math.abs(e.x - 2752) < 160) e.alive = false; __game.teleport(173, 12); });
await page.waitForTimeout(3000);
console.log('on lift:', await page.evaluate(() => ({ y: Math.round(__game.player.y), st: __game.player.standing, lift: Math.round(__game.level.lifts[3].y) })));
await shot('test/roof-ride');
await page.keyboard.down('ArrowRight');
await page.waitForTimeout(2500);
await page.keyboard.up('ArrowRight');
console.log('roof:', await page.evaluate(() => ({ x: Math.round(__game.player.x), y: Math.round(__game.player.y), feet: Math.round(__game.player.y + __game.player.h), st: __game.player.state })));
await shot('test/roof-walk');
await page.keyboard.down('ArrowRight');
await page.waitForTimeout(2500);
await page.keyboard.up('ArrowRight');
console.log('after drop:', await page.evaluate(() => ({ x: Math.round(__game.player.x), st: __game.player.state, lives: __game.player.lives, power: __game.player.power })));
await shot('test/roof-drop');
console.log(errs.length ? errs.slice(0,6).join('\n') : 'no errors');
process.exit(0);
