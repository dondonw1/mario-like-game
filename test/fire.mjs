import { createRequire } from 'module';
import { execSync } from 'child_process';
const require = createRequire(import.meta.url);
const { chromium } = require(execSync('npm root -g').toString().trim() + '/playwright-core');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9333');
const page = browser.contexts()[0].pages().find(p => p.url().includes('8123'));
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(500);
await page.keyboard.press('Enter');
await page.waitForTimeout(3000);
console.log('state:', await page.evaluate(() => ({ st: __game.state, power: __game.player.power })));
await page.evaluate(() => { __game.teleport(30, 11); __game.setPower(2); });
await page.waitForTimeout(500);
console.log('after setup:', await page.evaluate(() => ({ st: __game.state, power: __game.player.power, h: __game.player.h, y: Math.round(__game.player.y) })));
await page.evaluate(() => { __game.keys.run = 1; });
await page.waitForTimeout(300);
console.log('fireballs:', await page.evaluate(() => ({ n: __game.entities.filter(e => e.kind === 'fireball').length, run: __game.keys.run, power: __game.player.power })));
await page.evaluate(() => { __game.keys.run = 0; });
process.exit(0);
